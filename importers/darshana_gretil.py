"""GRETIL importer for the Darśana branch (Nyāya, Vaiśeṣika, Mīmāṃsā).

Kept separate from importers/gretil.py because the śāstra texts are structurally
unlike the smṛti/kāvya ones that module handles. Those are verse corpora with a
'// ABBR_canto.verse //' marker on every śloka. Nyāya and Mīmāṃsā are prose:
sūtra + bhāṣya + vārttika running together, segmented by section headings
(adhikaraṇa, āhnika, stabaka, adhyāya-pāda) rather than by verse number. So the
unit here is a SECTION, not a verse, and the parser is heading-driven.

Targets are the layer folders generated by tools/darshanas/scaffold_darshanas.py.
The scaffolder must have run first — this importer fills stubs, it does not
create them.

GRETIL is romanised IAST, not Devanagari; transliteration is a pipeline step
(common.iast_to_dev). Every file carries "COPYRIGHT AND TERMS OF USAGE AS FOR
SOURCE FILE", so the header's source-attribution block is captured verbatim into
source_note rather than discarded.

Run:  python importers/dispatch.py <id>
      python importers/darshana_gretil.py --list
"""

